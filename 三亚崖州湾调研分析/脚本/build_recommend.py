def hook_rows():
    out = []
    for group, items in GROUPS:
        for name, reason in items:
            r = rs.get(name)
            if r is None:
                out.append({'group': group, 'name': name, 'uscc': '未在名录中找到',
                            'tier': '', 'track': '', 'form': '', 'origin': '',
                            'vintage': '', 'reason': reason, 'flags': ''})
            else:
                out.append({'group': group, 'name': name, 'uscc': r['uscc'],
                            'tier': r['tier'], 'track': r['track'], 'form': r['form'],
                            'origin': r['origin'], 'vintage': r['vintage'],
                            'reason': reason, 'risk_flags': r['risk_flags']})
    return out


rows = hook_rows()
FIELDS = ['group', 'name', 'uscc', 'tier', 'track', 'form', 'origin',
          'vintage', 'reason', 'risk_flags']
with open('推荐名单.csv', 'w', newline='', encoding='utf-8-sig') as fh:
    w = csv.DictWriter(fh, fieldnames=FIELDS, extrasaction='ignore')
    w.writeheader()
    w.writerows(rows)

missing = [r['name'] for r in rows if r['uscc'] == '未在名录中找到']
print(f'推荐名单 {len(rows)} 家，写出 推荐名单.csv')
